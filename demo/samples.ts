import type { ImageInput } from 'intelligent-scissors';
import type { ImageSource } from 'intelligent-scissors/canvas';
import { createSyntheticImage } from './synthetic';

export interface Sample {
    id: string;
    label: string;
    /** Shown under the image. Required by the licences of the real images. */
    credit: string;
    /** Smoothing that suits the image; noisier images need more. */
    sigma: number;
    load(): Promise<ImageSource>;
    /** Raw grayscale samples can be re-windowed in the demo. */
    window?: { center: number; width: number };
}

const base = `${import.meta.env.BASE_URL}samples/`;

async function loadPicture(file: string): Promise<HTMLImageElement> {
    const img = new Image();
    img.src = base + file;
    await img.decode();
    return img;
}

/** 480 × 480, unsigned 16-bit little endian, one coronal slice. */
async function loadMri(): Promise<ImageInput> {
    const buffer = await (await fetch(base + 'mri-pelvis-t2.u16')).arrayBuffer();
    return { data: new Uint16Array(buffer), width: 480, height: 480 };
}

